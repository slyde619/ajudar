export function getCategoryBySlug(slug: string): TradeCategory | undefined {
  return categories.find((category) => category.slug === slug);
}

export function getCategoryById(id: string): TradeCategory | undefined {
  return categories.find((category) => category.id === id);
}

export function getCategoriesByTrade(trade: TradeCategory["trade"]): TradeCategory[] {
  return categories.filter((category) => category.trade === trade);
}
