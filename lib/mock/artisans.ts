function naira(amount: number): Kobo {
  return amount * 100;
}

function rateCard(
  callOutNaira: number,
  hourlyNaira: number,
  minimumNaira: number,
  transportPerKmNaira?: number,
): RateCard {
  return {
    callOutFee: naira(callOutNaira),
    hourlyRate: naira(hourlyNaira),
    minimumCharge: naira(minimumNaira),
    transportIncluded: transportPerKmNaira === undefined,
    transportFeePerKm:
      transportPerKmNaira === undefined ? undefined : naira(transportPerKmNaira),
    updatedAt: RATE_UPDATED,
  };
}

function coverage(
  homeLgaCode: string,
  servedLgaCodes: string[],
  driveTimeMinutes = 30,
): CoverageArea {
  return {
    homeLgaCode,
    servedLgaCodes,
    driveTimeMinutes,
    polygonGeoJSON: null,
    updatedAt: COVERAGE_UPDATED,
  };
}

